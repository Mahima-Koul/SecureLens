"""Generate validated single-file patches and apply them to an isolated copy."""

from __future__ import annotations

import difflib
import json
import shutil
import tempfile
from pathlib import Path, PurePosixPath
from pydantic import BaseModel, Field

from .llm import LLMClient
from .models import Finding, Patch
from .prompts import PATCH_SYSTEM_PROMPT


class PatchResponse(BaseModel):
    """Structured complete replacement file returned by the model."""

    patched_code: str
    explanation: str = Field(min_length=1)


def generate_patch(
    file_path: str | Path,
    confirmed_findings_for_that_file: list[Finding],
    *,
    project_dir: str | Path | None = None,
    llm_client: LLMClient | None = None,
) -> Patch:
    """Request a complete replacement file and produce its unified diff."""
    if not confirmed_findings_for_that_file:
        raise ValueError("At least one confirmed finding is required to generate a patch")
    source_path = Path(file_path).resolve()
    root = Path(project_dir).resolve() if project_dir is not None else source_path.parent
    try:
        relative = source_path.relative_to(root)
    except ValueError as exc:
        raise ValueError("Patch target is outside the selected project") from exc
    if not source_path.is_file() or source_path.suffix != ".py":
        raise ValueError("Patch target must be an existing Python source file")
    for finding in confirmed_findings_for_that_file:
        if Path(finding.file).as_posix() != relative.as_posix():
            raise ValueError("All confirmed findings must belong to the requested file")
    original = source_path.read_text(encoding="utf-8")
    evidence = {
        "file": relative.as_posix(),
        "complete_original_file": original,
        "confirmed_findings": [
            {"id": item.id, "rule_id": item.rule_id, "line": item.line, "message": item.message}
            for item in confirmed_findings_for_that_file
        ],
    }
    response = (llm_client or LLMClient()).complete(
        "patch", PATCH_SYSTEM_PROMPT,
        json.dumps(evidence, sort_keys=True, ensure_ascii=False), PatchResponse,
    )
    if not response.patched_code.strip():
        raise ValueError("The model returned an empty replacement file")
    diff = "".join(difflib.unified_diff(
        original.splitlines(keepends=True), response.patched_code.splitlines(keepends=True),
        fromfile=f"a/{relative.as_posix()}", tofile=f"b/{relative.as_posix()}",
    ))
    return Patch(
        file=relative.as_posix(), original_code=original, patched_code=response.patched_code,
        diff=diff, explanation=response.explanation.strip(),
        addressed_finding_ids=[item.id for item in confirmed_findings_for_that_file],
    )


def apply_patches(
    project_dir: str | Path,
    patches: list[Patch],
    *,
    workdir: str | Path | None = None,
) -> Path:
    """Copy a project to `workdir/<name>_patched` and change only that copy."""
    root = Path(project_dir).resolve()
    if not root.is_dir():
        raise ValueError(f"Project directory does not exist: {root}")
    output_root = Path(workdir or (Path.cwd() / "workdir")).resolve()
    try:
        output_root.relative_to(root)
    except ValueError:
        pass
    else:
        raise ValueError("Patched-copy workdir must be outside the original project")
    output_root.mkdir(parents=True, exist_ok=True)
    destination = output_root / f"{root.name}_patched"
    if destination.exists():
        raise FileExistsError(f"Patched copy already exists: {destination}; choose another workdir or remove that generated copy")
    _validate_patches(root, patches)
    stage = Path(tempfile.mkdtemp(prefix=f".{root.name}_patched_", dir=output_root))
    try:
        stage.rmdir()
        shutil.copytree(root, stage, symlinks=True, ignore=_copy_ignore)
        for patch in patches:
            target = _safe_target(stage, patch.file)
            if target.is_symlink():
                raise ValueError(f"Patch target is a symbolic link: {patch.file}")
            original = target.read_text(encoding="utf-8")
            if original != patch.original_code:
                raise ValueError(f"Patch source changed since generation: {patch.file}")
            target.write_text(patch.patched_code, encoding="utf-8", newline="")
        (stage / ".securelens-patched").write_text("Generated by SecureLens; do not edit the original project.\n", encoding="utf-8")
        stage.rename(destination)
        return destination
    except Exception:
        if stage.exists():
            shutil.rmtree(stage, ignore_errors=True)
        raise


def _validate_patches(root: Path, patches: list[Patch]) -> None:
    """Check every patch path and confirm the original source before copying."""
    seen: set[str] = set()
    for patch in patches:
        relative = PurePosixPath(patch.file)
        if relative.is_absolute() or not relative.parts or ".." in relative.parts or ":" in patch.file or "\\" in patch.file:
            raise ValueError(f"Unsafe patch path: {patch.file}")
        if patch.file in seen:
            raise ValueError(f"Multiple patches target the same file: {patch.file}")
        seen.add(patch.file)
        target = _safe_target(root, patch.file)
        if not target.is_file() or target.suffix != ".py":
            raise ValueError(f"Patch target is not an existing Python file: {patch.file}")
        if target.read_text(encoding="utf-8") != patch.original_code:
            raise ValueError(f"Patch source changed since generation: {patch.file}")


def _safe_target(root: Path, relative_path: str) -> Path:
    """Resolve a relative target and reject paths that escape the given root."""
    target = (root / Path(relative_path)).resolve()
    try:
        target.relative_to(root.resolve())
    except ValueError as exc:
        raise ValueError(f"Patch path escapes project: {relative_path}") from exc
    return target


def _copy_ignore(directory: str, names: list[str]) -> set[str]:
    """Skip repository metadata, caches, virtual environments, and prior copies."""
    ignored = {".git", ".venv", "venv", "__pycache__", ".cache", "workdir"}
    return {name for name in names if name in ignored or name.endswith("_patched")}
